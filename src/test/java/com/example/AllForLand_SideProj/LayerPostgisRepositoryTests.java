package com.example.AllForLand_SideProj;

import com.example.AllForLand_SideProj.customlayer.storage.LayerDocument;
import com.example.AllForLand_SideProj.customlayer.storage.LayerDocument.*;
import com.example.AllForLand_SideProj.customlayer.storage.db.DatabaseLayerRepository;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.UUID;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;
import org.postgresql.ds.PGSimpleDataSource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;
import org.springframework.web.server.ResponseStatusException;
import static org.junit.jupiter.api.Assertions.*;

/** Opt-in real PostGIS test. Creates and removes its own schema; never uses existing application tables. */
@EnabledIfEnvironmentVariable(named = "LAYER_DB_TEST_URL", matches = "jdbc:postgresql://localhost:5433/.*")
class LayerPostgisRepositoryTests {
    @Test
    void postgresRoundTripOwnershipStableIdsAndAtomicRollback() throws Exception {
        var source = new PGSimpleDataSource();
        source.setURL(System.getenv("LAYER_DB_TEST_URL"));
        source.setUser(System.getenv("LAYER_DB_TEST_USER"));
        source.setPassword(System.getenv("LAYER_DB_TEST_PASSWORD"));
        String schema = "layer_test_" + UUID.randomUUID().toString().replace("-", "");
        try (var connection = source.getConnection(); var admin = connection.createStatement()) {
            admin.execute("CREATE SCHEMA " + schema);
            try {
                source.setCurrentSchema(schema + ",public");
                var jdbc = new JdbcTemplate(source);
                jdbc.execute("CREATE TABLE users (user_id BIGINT PRIMARY KEY, login_id VARCHAR(50) UNIQUE)");
                jdbc.execute("""
                    CREATE TABLE user_custom_layers (custom_layer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id BIGINT NOT NULL REFERENCES users(user_id), layer_name VARCHAR(100) NOT NULL,
                        description TEXT, is_public BOOLEAN NOT NULL, created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL)
                    """);
                try (var migrationConnection = source.getConnection(); var migration = migrationConnection.createStatement()) {
                    migration.execute(Files.readString(Path.of("docs/sql/custom-layer-storage.sql")));
                }
                jdbc.update("INSERT INTO users VALUES (1, 'first'), (2, 'second')");
                var repository = new DatabaseLayerRepository(new NamedParameterJdbcTemplate(source));
                var transaction = new TransactionTemplate(new DataSourceTransactionManager(source));
                var points = List.of(new Point(51.5, -0.2), new Point(51.6, -0.2), new Point(51.5, -0.1));
                var shapes = List.of(new Shape("marker", "#247b65", null, points.getFirst(), null, null),
                    new Shape("circle", "#247b65", null, points.getFirst(), null, 150.0),
                    new Shape("polyline", "#247b65", points, null, null, null),
                    new Shape("polygon", "#247b65", points, null, null, null),
                    new Shape("rectangle", "#247b65", null, null, new Bounds(52.0, 51.0, 1.0, -1.0), null));
                var features = new java.util.ArrayList<Feature>();
                for (int i = 0; i < shapes.size(); i++) features.add(new Feature(i + 1, "Item " + i, i + 1, "18:30", true, null, shapes.get(i)));
                var layer = new LayerDocument(List.copyOf(features));
                transaction.executeWithoutResult(status -> repository.replaceAll("1", layer));
                transaction.executeWithoutResult(status -> repository.replaceAll("2", layer));
                assertEquals(layer, repository.findAll("1"));
                Long id = jdbc.queryForObject("SELECT custom_layer_id FROM user_custom_layers WHERE user_id = 1", Long.class);
                var edited = new LayerDocument(List.of(new Feature(1, "Edited", 10, "20:00", false, null, shapes.getFirst())));
                transaction.executeWithoutResult(status -> repository.replaceAll("1", edited));
                assertEquals(id, jdbc.queryForObject("SELECT custom_layer_id FROM user_custom_layers WHERE user_id = 1", Long.class));
                assertEquals(edited, repository.findAll("1"));
                assertEquals(layer, repository.findAll("2"));
                assertEquals(1, jdbc.queryForObject("SELECT count(*) FROM user_custom_layers WHERE user_id = 1 AND is_personal", Integer.class));
                var invalid = new LayerDocument(List.of(new Feature(1, "Must rollback", 9, "18:30", true, null,
                    new Shape("polygon", "#247b65", List.of(new Point(0.0, 0.0), new Point(1.0, 1.0),
                        new Point(0.0, 1.0), new Point(1.0, 0.0)), null, null, null))));
                assertThrows(ResponseStatusException.class, () -> transaction.executeWithoutResult(status -> repository.replaceAll("1", invalid)));
                assertEquals(edited, repository.findAll("1"));
                repository.deleteWorkspace("1"); // Session cleanup is intentionally a no-op for a database.
                assertEquals(edited, repository.findAll("1"));
                transaction.executeWithoutResult(status -> repository.replaceAll("1", new LayerDocument(List.of())));
                assertTrue(repository.findAll("1").features().isEmpty());
                assertEquals(layer, repository.findAll("2"));
                assertEquals(5, jdbc.queryForObject("SELECT count(*) FROM custom_layer_features", Integer.class));
                String guest = UUID.randomUUID().toString();
                transaction.executeWithoutResult(status -> repository.replaceAll(guest, layer));
                transaction.executeWithoutResult(status -> repository.replaceAll(guest, edited));
                assertEquals(edited, repository.findAll(guest));
                assertTrue(repository.findAll(UUID.randomUUID().toString()).features().isEmpty());
                assertEquals(layer, repository.findAll("2"));
                assertEquals(1, jdbc.queryForObject("SELECT count(*) FROM user_custom_layers WHERE user_id IS NULL AND is_personal", Integer.class));
            } finally { admin.execute("DROP SCHEMA " + schema + " CASCADE"); }
        }
    }
}
