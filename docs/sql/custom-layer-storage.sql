-- Single personal layer per user. Apply manually after original ERD tables exist.
-- Existing layers/custom_markers are not deleted or automatically converted.
BEGIN;
CREATE EXTENSION IF NOT EXISTS postgis;
ALTER TABLE user_custom_layers ADD COLUMN IF NOT EXISTS is_personal BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE user_custom_layers ALTER COLUMN user_id DROP NOT NULL;
ALTER TABLE user_custom_layers ADD COLUMN IF NOT EXISTS anonymous_key VARCHAR(36);
CREATE UNIQUE INDEX IF NOT EXISTS ux_user_personal_layer ON user_custom_layers(user_id) WHERE is_personal = TRUE;
CREATE UNIQUE INDEX IF NOT EXISTS ux_anonymous_personal_layer ON user_custom_layers(anonymous_key) WHERE is_personal = TRUE;
CREATE TABLE IF NOT EXISTS custom_layer_features (
    feature_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    custom_layer_id BIGINT NOT NULL REFERENCES user_custom_layers(custom_layer_id) ON DELETE CASCADE,
    client_feature_id BIGINT NOT NULL,
    title VARCHAR(100) NOT NULL,
    visit_month SMALLINT NOT NULL CHECK (visit_month BETWEEN 1 AND 12),
    visit_time TIME NOT NULL,
    is_visible BOOLEAN NOT NULL DEFAULT TRUE,
    photo_data TEXT,
    shape_type VARCHAR(16) NOT NULL CHECK (shape_type IN ('marker','polyline','polygon','rectangle','circle')),
    color VARCHAR(7) NOT NULL CHECK (color ~ '^#[0-9A-Fa-f]{6}$'),
    geometry geometry(Geometry,4326) NOT NULL,
    radius_m DOUBLE PRECISION,
    display_order INT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(custom_layer_id, display_order),
    UNIQUE(custom_layer_id, client_feature_id),
    CHECK (ST_IsValid(geometry) AND NOT ST_IsEmpty(geometry)),
    CHECK ((shape_type IN ('marker','circle') AND GeometryType(geometry) = 'POINT')
        OR (shape_type = 'polyline' AND GeometryType(geometry) = 'LINESTRING')
        OR (shape_type IN ('polygon','rectangle') AND GeometryType(geometry) = 'POLYGON')),
    CHECK ((shape_type = 'circle' AND radius_m IS NOT NULL AND radius_m > 0 AND radius_m <= 20000000)
        OR (shape_type <> 'circle' AND radius_m IS NULL))
);
-- Compatibility additions if the old preparation SQL was manually applied.
-- Old rows remain attached to non-personal layers and are not exposed by the editor.
ALTER TABLE custom_layer_features
    ADD COLUMN IF NOT EXISTS client_feature_id BIGINT,
    ADD COLUMN IF NOT EXISTS title VARCHAR(100),
    ADD COLUMN IF NOT EXISTS visit_month SMALLINT,
    ADD COLUMN IF NOT EXISTS visit_time TIME,
    ADD COLUMN IF NOT EXISTS is_visible BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN IF NOT EXISTS photo_data TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS ux_custom_layer_feature_client ON custom_layer_features(custom_layer_id, client_feature_id);
CREATE INDEX IF NOT EXISTS ix_custom_layer_features_geometry ON custom_layer_features USING GIST(geometry);
CREATE INDEX IF NOT EXISTS ix_custom_features_visit ON custom_layer_features(custom_layer_id, visit_month, visit_time);
COMMIT;
